alter table public.grace_workspace_members
  add column if not exists auth_user_id uuid references auth.users(id) on delete set null;

create unique index if not exists grace_workspace_members_auth_user_uidx
  on public.grace_workspace_members(auth_user_id)
  where auth_user_id is not null;

alter table public.grace_social_accounts
  add column if not exists approval_required boolean not null default true,
  add column if not exists emergency_disabled boolean not null default false,
  add column if not exists last_successful_post_at timestamptz,
  add column if not exists last_error text;

create table if not exists public.grace_account_permissions (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.grace_workspaces(id) on delete cascade,
  account_id bigint not null references public.grace_social_accounts(id) on delete cascade,
  telegram_id bigint not null,
  can_create boolean not null default true,
  can_schedule boolean not null default false,
  can_publish boolean not null default false,
  can_approve boolean not null default false,
  created_by bigint,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(account_id, telegram_id)
);

create index if not exists grace_account_permissions_workspace_idx
  on public.grace_account_permissions(workspace_id, telegram_id);

create table if not exists public.grace_publish_results (
  id bigint generated by default as identity primary key,
  workspace_id uuid not null references public.grace_workspaces(id) on delete cascade,
  post_id uuid not null references public.grace_posts(id) on delete cascade,
  target_id bigint references public.grace_post_targets(id) on delete set null,
  account_id bigint not null references public.grace_social_accounts(id) on delete cascade,
  status text not null check (status in ('published','failed','blocked','cancelled')),
  platform_response jsonb not null default '{}'::jsonb,
  external_post_id text,
  error_code text,
  error_message text,
  published_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists grace_publish_results_post_idx
  on public.grace_publish_results(workspace_id, post_id, created_at desc);
create index if not exists grace_publish_results_account_idx
  on public.grace_publish_results(account_id, created_at desc);

alter table public.grace_account_permissions enable row level security;
alter table public.grace_publish_results enable row level security;

revoke all on public.grace_account_permissions from anon, authenticated;
revoke all on public.grace_publish_results from anon, authenticated;
grant all on public.grace_account_permissions to service_role;
grant all on public.grace_publish_results to service_role;

grant usage, select on sequence public.grace_account_permissions_id_seq to service_role;
grant usage, select on sequence public.grace_publish_results_id_seq to service_role;
