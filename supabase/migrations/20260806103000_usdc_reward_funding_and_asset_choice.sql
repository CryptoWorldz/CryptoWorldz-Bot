on conflict (id) do update set
  network = excluded.network,
  funding_asset = excluded.funding_asset,
  default_payout_asset = excluded.default_payout_asset,
  allowed_payout_assets = excluded.allowed_payout_assets,
  weekly_target_aud_cents = excluded.weekly_target_aud_cents,
  weekly_target_points = excluded.weekly_target_points,
  timezone = excluded.timezone,
  sol_conversion_policy = excluded.sol_conversion_policy,
  auto_transfer_enabled = excluded.auto_transfer_enabled,
  updated_at = now();

create table if not exists public.reward_funding_schedule (
  day_of_week smallint primary key check (day_of_week between 1 and 7),
  day_label text not null,
  planned_aud_cents integer not null check (planned_aud_cents > 0),
  display_order smallint not null check (display_order > 0),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

