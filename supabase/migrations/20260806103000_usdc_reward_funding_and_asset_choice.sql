create table if not exists public.reward_funding_settings (
  id text primary key default 'global',
  network text not null default 'solana' check (network = 'solana'),
  funding_asset text not null default 'USDC' check (funding_asset = 'USDC'),
  default_payout_asset text not null default 'USDC' check (default_payout_asset in ('USDC', 'SOL')),
  allowed_payout_assets text[] not null default array['USDC', 'SOL']::text[],
  weekly_target_aud_cents integer not null default 8000 check (weekly_target_aud_cents between 0 and 8000),
  weekly_target_points integer not null default 3000 check (weekly_target_points between 0 and 3000),
  timezone text not null default 'Australia/Sydney',
  sol_conversion_policy text not null default 'quote_at_payout' check (sol_conversion_policy = 'quote_at_payout'),
  auto_transfer_enabled boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint reward_funding_settings_singleton check (id = 'global'),
  constraint allowed_reward_assets check (
    allowed_payout_assets <@ array['USDC', 'SOL']::text[]
    and array_length(allowed_payout_assets, 1) >= 1
  )
);

