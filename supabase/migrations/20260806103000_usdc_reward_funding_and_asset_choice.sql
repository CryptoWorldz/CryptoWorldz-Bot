create or replace function public.current_reward_week_start()
returns date
language sql
stable
set search_path = ''
as $$
  select (
    (now() at time zone 'Australia/Sydney')::date
    - (extract(isodow from now() at time zone 'Australia/Sydney')::integer - 1)
  )::date
$$;

create or replace function public.record_reward_funding_deposit(
  p_aud_value_cents integer,
  p_usdc_amount numeric,
  p_transaction_signature text,
  p_recorded_by bigint
)
returns table(
  outcome text,
  deposit_id bigint,
  weekly_recorded_aud_cents integer,
  weekly_remaining_aud_cents integer
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_settings public.reward_funding_settings%rowtype;
  v_week_start date := public.current_reward_week_start();
  v_day smallint := extract(isodow from now() at time zone 'Australia/Sydney')::smallint;
  v_used integer := 0;
  v_deposit_id bigint;
  v_signature text := trim(coalesce(p_transaction_signature, ''));
begin
  if p_aud_value_cents is null or p_aud_value_cents <= 0 then
    return query select 'invalid_aud_value'::text, null::bigint, 0, 0;
    return;
  end if;

  if p_usdc_amount is null or p_usdc_amount <= 0 then
    return query select 'invalid_usdc_amount'::text, null::bigint, 0, 0;
    return;
  end if;

  if v_signature !~ '^[1-9A-HJ-NP-Za-km-z]{40,100}$' then
    return query select 'invalid_transaction_signature'::text, null::bigint, 0, 0;
    return;
  end if;

  select * into v_settings
  from public.reward_funding_settings
  where id = 'global'
  for update;

  select coalesce(sum(aud_value_cents), 0)::integer into v_used
  from public.reward_funding_deposits
  where reward_week_start = v_week_start
    and status in ('recorded', 'verified');

  if v_used + p_aud_value_cents > v_settings.weekly_target_aud_cents then
    return query select
      'weekly_target_exceeded'::text,
      null::bigint,
      v_used,
      greatest(v_settings.weekly_target_aud_cents - v_used, 0);
    return;
  end if;

  begin
    insert into public.reward_funding_deposits (
      reward_week_start,
      recorded_day_of_week,
      aud_value_cents,
      asset,
      asset_amount,
      transaction_signature,
      status,
      recorded_by
    ) values (
      v_week_start,
      v_day,
      p_aud_value_cents,
      'USDC',
      p_usdc_amount,
      v_signature,
      'recorded',
      p_recorded_by
    )
    returning id into v_deposit_id;
  exception
    when unique_violation then
      return query select
        'duplicate_transaction'::text,
        null::bigint,
        v_used,
        greatest(v_settings.weekly_target_aud_cents - v_used, 0);
      return;
  end;

  v_used := v_used + p_aud_value_cents;
  return query select
    'recorded'::text,
    v_deposit_id,
    v_used,
    greatest(v_settings.weekly_target_aud_cents - v_used, 0);
end;
$$;

create or replace function public.get_reward_funding_status()
returns table(
  reward_week_start date,
  network text,
  funding_asset text,
  default_payout_asset text,
  allowed_payout_assets text[],
  weekly_target_aud_cents integer,
  weekly_target_points integer,
  recorded_aud_cents integer,
  remaining_aud_cents integer,
  timezone text,
  sol_conversion_policy text,
  auto_transfer_enabled boolean,
  funding_schedule jsonb
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_settings public.reward_funding_settings%rowtype;
  v_week_start date := public.current_reward_week_start();
  v_recorded integer := 0;
  v_schedule jsonb := '[]'::jsonb;
begin
  select * into v_settings
  from public.reward_funding_settings
  where id = 'global';

  select coalesce(sum(aud_value_cents), 0)::integer into v_recorded
  from public.reward_funding_deposits
  where reward_week_start = v_week_start
    and status in ('recorded', 'verified');

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'day_of_week', day_of_week,
        'day_label', day_label,
        'planned_aud_cents', planned_aud_cents
      ) order by display_order
    ),
    '[]'::jsonb
  ) into v_schedule
  from public.reward_funding_schedule
  where active = true;

  return query select
    v_week_start,
    v_settings.network,
    v_settings.funding_asset,
    v_settings.default_payout_asset,
    v_settings.allowed_payout_assets,
    v_settings.weekly_target_aud_cents,
    v_settings.weekly_target_points,
    v_recorded,
    greatest(v_settings.weekly_target_aud_cents - v_recorded, 0),
    v_settings.timezone,
    v_settings.sol_conversion_policy,
    v_settings.auto_transfer_enabled,
    v_schedule;
end;
$$;

