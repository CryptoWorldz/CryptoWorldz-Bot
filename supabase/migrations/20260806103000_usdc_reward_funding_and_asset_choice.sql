create table if not exists public.member_reward_preferences (
  telegram_id bigint primary key,
  preferred_asset text not null default 'USDC' check (preferred_asset in ('USDC', 'SOL')),
  network text not null default 'solana' check (network = 'solana'),
  conversion_policy text not null default 'quote_at_payout' check (conversion_policy = 'quote_at_payout'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.reward_funding_deposits (
  id bigint generated by default as identity primary key,
  reward_week_start date not null,
  recorded_day_of_week smallint not null check (recorded_day_of_week between 1 and 7),
  aud_value_cents integer not null check (aud_value_cents > 0),
  asset text not null default 'USDC' check (asset = 'USDC'),
  asset_amount numeric(20, 8) not null check (asset_amount > 0),
  transaction_signature text not null unique,
  status text not null default 'recorded' check (status in ('recorded', 'verified', 'void')),
  recorded_by bigint not null,
  created_at timestamptz not null default now(),
  verified_at timestamptz,
  updated_at timestamptz not null default now()
);

create index if not exists reward_funding_deposits_week_idx
  on public.reward_funding_deposits (reward_week_start, status, created_at);

