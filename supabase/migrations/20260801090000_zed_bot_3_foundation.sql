-- Mirror future legacy reward writes into the canonical transaction ledger.
create or replace function public.mirror_legacy_reward_transaction() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.reward_transactions(telegram_id, mission_id, amount, reward_type, reason, created_at)
  values (new.telegram_id, new.mission_id, new.points,
    case when new.reward_type = 'manual_adjustment' then 'admin_adjustment' else 'mission' end,
    coalesce(nullif(new.description,''), 'Zed reward'), new.created_at);
  return new;
end $$;
revoke all on function public.mirror_legacy_reward_transaction() from public, anon, authenticated;
grant execute on function public.mirror_legacy_reward_transaction() to service_role;
drop trigger if exists rewards_mirror_transaction on public.rewards;
create trigger rewards_mirror_transaction after insert on public.rewards
for each row execute function public.mirror_legacy_reward_transaction();
