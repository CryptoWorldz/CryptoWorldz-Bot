-- ZED Auto Kitty Rewards.
-- ZED calculates proportional reward amounts from completed-week Legend Points.
-- Humans may approve the locked amount, but cannot edit the formula or payout amount.

create table if not exists public.reward_auto_settings (
  id text primary key default 'global' check (id = 'global'),
  enabled boolean not null default true,
  pool_percent numeric(5,2) not null default 10.00 check (pool_percent > 0 and pool_percent <= 50),
  minimum_kitty_usdc numeric(30,6) not null default 100.000000 check (minimum_kitty_usdc >= 0),
  minimum_batch_usdc numeric(30,6) not null default 1.000000 check (minimum_batch_usdc >= 0),
  timezone text not null default 'Australia/Sydney',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

insert into public.reward_auto_settings (
  id, enabled, pool_percent, minimum_kitty_usdc, minimum_batch_usdc, timezone
) values (
  'global', true, 10.00, 100.000000, 1.000000, 'Australia/Sydney'
)
on conflict (id) do nothing;

create table if not exists public.reward_auto_batches (
  id bigint generated by default as identity primary key,
  reward_week_start date not null unique,
  kitty_snapshot_usdc numeric(30,6) not null check (kitty_snapshot_usdc >= 0),
  available_kitty_usdc numeric(30,6) not null check (available_kitty_usdc >= 0),
  pool_percent numeric(5,2) not null check (pool_percent > 0 and pool_percent <= 50),
  pool_usdc numeric(30,6) not null check (pool_usdc >= 0),
  allocated_usdc numeric(30,6) not null default 0 check (allocated_usdc >= 0),
  points_total integer not null check (points_total > 0),
  queued_count integer not null default 0 check (queued_count >= 0),
  status text not null default 'waiting_approval'
    check (status in ('waiting_approval','partially_approved','approved','closed')),
  generated_by bigint,
  generated_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.reward_auto_queue (
  id bigint generated by default as identity primary key,
  batch_id bigint not null references public.reward_auto_batches(id) on delete restrict,
  telegram_id bigint not null,
  legend_points integer not null check (legend_points > 0),
  share_percent numeric(12,6) not null check (share_percent >= 0 and share_percent <= 100),
  usdc_amount numeric(30,6) not null check (usdc_amount > 0),
  preferred_asset text not null default 'USDC' check (preferred_asset in ('USDC','SOL')),
  wallet_address text,
  status text not null default 'pending_approval'
    check (status in ('pending_approval','wallet_required','approved','paid','cancelled')),
  approved_by bigint,
  approved_at timestamptz,
  payout_signature text,
  paid_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (batch_id, telegram_id)
);

create index if not exists reward_auto_queue_status_idx
  on public.reward_auto_queue(status, created_at);
create index if not exists reward_auto_queue_telegram_idx
  on public.reward_auto_queue(telegram_id, created_at desc);

alter table public.reward_auto_settings enable row level security;
alter table public.reward_auto_batches enable row level security;
alter table public.reward_auto_queue enable row level security;

revoke all on public.reward_auto_settings, public.reward_auto_batches, public.reward_auto_queue
