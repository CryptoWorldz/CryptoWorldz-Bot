create table if not exists public.secureguard_evidence (
  id bigint generated by default as identity primary key,
  subject_telegram_id bigint not null check (subject_telegram_id > 0),
  source_key text not null references public.secureguard_intel_sources(source_key) on update cascade on delete restrict,
  source_reference text,
  signal_type text not null default 'risk_signal',
  severity integer not null default 50 check (severity between 0 and 100),
  source_confidence integer not null default 50 check (source_confidence between 0 and 100),
  evidence_url text,
  evidence text not null default '',
  metadata jsonb not null default '{}'::jsonb,
  status text not null default 'active' check (status in ('active','dismissed','expired')),
  observed_at timestamptz not null default now(),
  expires_at timestamptz,
  created_by_telegram_id bigint,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists secureguard_evidence_subject_active_idx
  on public.secureguard_evidence(subject_telegram_id,status,observed_at desc);
create index if not exists secureguard_evidence_source_idx
  on public.secureguard_evidence(source_key,status,observed_at desc);

create table if not exists public.secureguard_appeals (
  id bigint generated by default as identity primary key,
  subject_telegram_id bigint not null check (subject_telegram_id > 0),
  appellant_telegram_id bigint not null check (appellant_telegram_id > 0),
  chat_id bigint,
  reason text not null,
  evidence_url text,
  evidence text not null default '',
  status text not null default 'pending'
    check (status in ('pending','under_review','granted','denied','withdrawn')),
  reviewer_telegram_id bigint,
  review_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  resolved_at timestamptz
);
create unique index if not exists secureguard_appeals_one_active_subject_idx
  on public.secureguard_appeals(subject_telegram_id)
  where status in ('pending','under_review');
create index if not exists secureguard_appeals_status_idx
  on public.secureguard_appeals(status,created_at asc);

create table if not exists public.secureguard_assessments (
  id bigint generated by default as identity primary key,
  subject_telegram_id bigint not null check (subject_telegram_id > 0),
  risk_score integer not null check (risk_score between 0 and 100),
  risk_band text not null
    check (risk_band in ('clear','watch','quarantine','block_candidate','blocked')),
  recommended_action text not null
    check (recommended_action in ('allow','watch','quarantine','local_block','network_block')),
  source_count integer not null default 0 check (source_count >= 0),
  independent_source_count integer not null default 0 check (independent_source_count >= 0),
  active_appeal boolean not null default false,
  rationale jsonb not null default '{}'::jsonb,
  assessed_at timestamptz not null default now()
);
create index if not exists secureguard_assessments_subject_idx
  on public.secureguard_assessments(subject_telegram_id,assessed_at desc);

