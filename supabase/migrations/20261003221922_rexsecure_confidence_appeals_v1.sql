create table if not exists public.secureguard_intel_sources (
  source_key text primary key,
  display_name text not null,
  source_type text not null
    check (source_type in ('provider','worldz_adjudication','admin_report','behavior','pattern','identity')),
  base_weight integer not null
    check (base_weight between 0 and 100),
  max_auto_action text not null default 'watch'
    check (max_auto_action in ('observe','watch','quarantine','local_block','network_block')),
  requires_corroboration boolean not null default true,
  freshness_hours integer
    check (freshness_hours is null or freshness_hours between 1 and 87600),
  attribution text not null default '',
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

