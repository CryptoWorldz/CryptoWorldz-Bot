-- Non-destructive Zed Bot mission and rewards workflow.
-- Existing users, wallets, missions, submissions and rewards are preserved.

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  telegram_id bigint not null unique,
  username text,
  first_name text,
  wallet text,
  points integer not null default 0,
  raids integer not null default 0,
  raids_completed integer default 0,
  registered_at timestamp without time zone default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_checkin date
);

alter table public.users
  add column if not exists username text,
  add column if not exists first_name text,
  add column if not exists wallet text,
  add column if not exists points integer default 0,
  add column if not exists raids integer default 0,
  add column if not exists raids_completed integer default 0,
  add column if not exists registered_at timestamp without time zone default now(),
  add column if not exists created_at timestamptz default now(),
  add column if not exists updated_at timestamptz default now(),
  add column if not exists last_checkin date;

create table if not exists public.missions (
  id bigint generated by default as identity primary key,
  title text not null,
  platform text not null,
  target_url text not null default '',
  link text not null default '',
  reward_points integer not null default 5,
  status text not null default 'open',
  description text not null default '',
  instructions text not null default '',
  created_by bigint,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  completed_at timestamptz
);

alter table public.missions
  add column if not exists target_url text default '',
  add column if not exists link text default '',
  add column if not exists reward_points integer default 5,
  add column if not exists status text default 'open',
  add column if not exists description text default '',
  add column if not exists instructions text default '',
  add column if not exists created_by bigint,
  add column if not exists created_at timestamptz default now(),
  add column if not exists updated_at timestamptz default now(),
  add column if not exists completed_at timestamptz;

create table if not exists public.mission_submissions (
  id bigint generated by default as identity primary key,
  mission_id bigint not null references public.missions(id) on delete cascade,
  telegram_id bigint not null,
  proof_url text not null default '',
  completion_text text,
  status text not null default 'pending',
  points_awarded integer not null default 0,
  submitted_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewer_telegram_id bigint,
  rejection_reason text,
  updated_at timestamptz not null default now()
);

alter table public.mission_submissions
  add column if not exists proof_url text default '',
  add column if not exists completion_text text,
  add column if not exists status text default 'pending',
  add column if not exists points_awarded integer default 0,
  add column if not exists submitted_at timestamptz default now(),
  add column if not exists reviewed_at timestamptz,
  add column if not exists reviewer_telegram_id bigint,
  add column if not exists rejection_reason text,
  add column if not exists updated_at timestamptz default now();

create table if not exists public.rewards (
  id bigint generated by default as identity primary key,
  telegram_id bigint not null,
  mission_id bigint references public.missions(id) on delete set null,
  points integer not null default 0,
  reward_type text not null default 'mission_points',
  description text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.mission_history (
  id bigint generated by default as identity primary key,
  mission_id bigint references public.missions(id) on delete cascade,
  action text not null,
  actor_telegram_id bigint,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.users'::regclass and conname = 'users_points_nonnegative'
  ) then
    alter table public.users
      add constraint users_points_nonnegative check (coalesce(points, 0) >= 0);
  end if;

  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.missions'::regclass and conname = 'missions_reward_points_check'
  ) then
    alter table public.missions
      add constraint missions_reward_points_check check (reward_points >= 0);
  end if;

  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.missions'::regclass and conname = 'missions_status_check'
  ) then
    alter table public.missions
      add constraint missions_status_check
      check (status in ('active', 'open', 'completed', 'closed', 'cancelled'));
  end if;

  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.mission_submissions'::regclass
      and conname = 'mission_submissions_mission_id_telegram_id_key'
  ) then
    alter table public.mission_submissions
      add constraint mission_submissions_mission_id_telegram_id_key
      unique (mission_id, telegram_id);
  end if;

  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.mission_submissions'::regclass
      and conname = 'mission_submissions_status_check'
  ) then
    alter table public.mission_submissions
      add constraint mission_submissions_status_check
      check (status in ('pending', 'approved', 'rejected'));
  end if;

  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.mission_submissions'::regclass
      and conname = 'mission_submissions_points_awarded_check'
  ) then
    alter table public.mission_submissions
      add constraint mission_submissions_points_awarded_check
      check (points_awarded >= 0);
  end if;

  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.rewards'::regclass and conname = 'rewards_points_check'
  ) then
    alter table public.rewards
      add constraint rewards_points_check
      check (points >= 0 or reward_type = 'manual_adjustment');
  end if;
end
$$;

create index if not exists missions_status_created_idx
  on public.missions (status, created_at desc, id desc);
create index if not exists mission_submissions_status_idx
  on public.mission_submissions (status, submitted_at);
create index if not exists mission_submissions_user_status_idx
  on public.mission_submissions (telegram_id, status);
create index if not exists rewards_telegram_created_idx
  on public.rewards (telegram_id, created_at desc);
create index if not exists mission_history_mission_created_idx
  on public.mission_history (mission_id, created_at desc);

