create or replace function public.approve_mission_completion(
  p_submission_id bigint,
  p_reviewer_telegram_id bigint
)
returns table(
  submission_id bigint,
  telegram_id bigint,
  awarded_points integer,
  total_points integer,
  total_raids integer,
  mission_title text,
  already_awarded boolean
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_submission public.mission_submissions%rowtype;
  v_mission public.missions%rowtype;
  v_user public.users%rowtype;
begin
  select * into v_submission
  from public.mission_submissions s
  where s.id = p_submission_id
  for update;

  if not found then raise exception 'submission_not_found'; end if;
  if v_submission.status = 'rejected' then raise exception 'submission_rejected'; end if;

  select * into v_mission
  from public.missions m
  where m.id = v_submission.mission_id;
  if not found then raise exception 'mission_not_found'; end if;

  select * into v_user
  from public.users u
  where u.telegram_id = v_submission.telegram_id
  for update;
  if not found then raise exception 'user_not_registered'; end if;

  if v_submission.status = 'approved' then
    return query select
      v_submission.id,
      v_submission.telegram_id,
      coalesce(v_submission.points_awarded, 0),
      coalesce(v_user.points, 0),
      greatest(coalesce(v_user.raids_completed, 0), coalesce(v_user.raids, 0)),
      v_mission.title,
      true;
    return;
  end if;

  update public.users u
  set points = coalesce(u.points, 0) + v_mission.reward_points,
      raids = coalesce(u.raids, 0) + 1,
      raids_completed = coalesce(u.raids_completed, 0) + 1,
      updated_at = now()
  where u.telegram_id = v_submission.telegram_id
  returning u.* into v_user;

  update public.mission_submissions s
  set status = 'approved',
      points_awarded = v_mission.reward_points,
      reviewer_telegram_id = p_reviewer_telegram_id,
      reviewed_at = now(),
      rejection_reason = null,
      updated_at = now()
  where s.id = v_submission.id;

  insert into public.rewards (
    telegram_id, mission_id, points, reward_type, description
  ) values (
    v_submission.telegram_id,
    v_submission.mission_id,
    v_mission.reward_points,
    'mission_points',
    'Raaiiidd mission completion'
  );

  insert into public.mission_history (
    mission_id, action, actor_telegram_id, details
  ) values (
    v_submission.mission_id,
    'claim_approved',
    p_reviewer_telegram_id,
    jsonb_build_object(
      'submission_id', v_submission.id,
      'telegram_id', v_submission.telegram_id,
      'points', v_mission.reward_points
    )
  );

  return query select
    v_submission.id,
    v_submission.telegram_id,
    v_mission.reward_points,
    coalesce(v_user.points, 0),
    greatest(coalesce(v_user.raids_completed, 0), coalesce(v_user.raids, 0)),
    v_mission.title,
    false;
end;
$$;

revoke all on function public.approve_mission_completion(bigint, bigint)
  from public, anon, authenticated;
grant execute on function public.approve_mission_completion(bigint, bigint)
  to service_role;

create or replace function public.adjust_legend_points(
  p_target_telegram_id bigint,
  p_amount integer,
  p_admin_telegram_id bigint
)
returns table(telegram_id bigint, adjustment integer, total_points integer)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user public.users%rowtype;
  v_total integer;
begin
  if p_amount = 0 or p_amount < -10000 or p_amount > 10000 then
    raise exception 'invalid_adjustment';
  end if;

  select * into v_user
  from public.users u
  where u.telegram_id = p_target_telegram_id
  for update;
  if not found then raise exception 'user_not_registered'; end if;

  v_total := coalesce(v_user.points, 0) + p_amount;
  if v_total < 0 then raise exception 'points_cannot_be_negative'; end if;

  update public.users u
  set points = v_total, updated_at = now()
  where u.telegram_id = p_target_telegram_id;

  insert into public.rewards (
    telegram_id, mission_id, points, reward_type, description
  ) values (
    p_target_telegram_id,
    null,
    p_amount,
    'manual_adjustment',
    'Administrator Legend Points adjustment'
  );

  insert into public.mission_history (
    mission_id, action, actor_telegram_id, details
  ) values (
    null,
    'points_adjusted',
    p_admin_telegram_id,
    jsonb_build_object(
      'telegram_id', p_target_telegram_id,
      'amount', p_amount,
      'total_points', v_total
    )
  );

  return query select p_target_telegram_id, p_amount, v_total;
end;
$$;

revoke all on function public.adjust_legend_points(bigint, integer, bigint)
  from public, anon, authenticated;
grant execute on function public.adjust_legend_points(bigint, integer, bigint)
  to service_role;
