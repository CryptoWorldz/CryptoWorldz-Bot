create table if not exists public.reward_budget_settings (
  id text primary key default 'global',
  currency text not null default 'AUD',
  weekly_budget_cents integer not null default 0 check (weekly_budget_cents >= 0),
  points_per_currency_unit integer not null default 100 check (points_per_currency_unit between 1 and 100000),
  utilization_percent integer not null default 70 check (utilization_percent between 1 and 100),
  pilot_weekly_points_cap integer not null default 1000 check (pilot_weekly_points_cap > 0),
  maximum_weekly_points_cap integer not null default 5000 check (maximum_weekly_points_cap >= pilot_weekly_points_cap),
  mission_pool_percent integer not null default 50 check (mission_pool_percent between 0 and 100),
  referral_pool_percent integer not null default 30 check (referral_pool_percent between 0 and 100),
  reserve_pool_percent integer not null default 20 check (reserve_pool_percent between 0 and 100),
  referral_inviter_points integer not null default 20 check (referral_inviter_points between 1 and 1000),
  referral_newcomer_points integer not null default 5 check (referral_newcomer_points between 0 and 1000),
  referral_retention_days integer not null default 7 check (referral_retention_days between 1 and 90),
  inviter_weekly_qualified_cap integer not null default 5 check (inviter_weekly_qualified_cap between 1 and 100),
  enabled boolean not null default true,
  cash_redemption_enabled boolean not null default false,
  updated_by bigint,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint reward_budget_singleton check (id = 'global'),
  constraint reward_budget_pool_total check (
    mission_pool_percent + referral_pool_percent + reserve_pool_percent = 100
  )
);

insert into public.reward_budget_settings (id)
values ('global')
on conflict (id) do nothing;

