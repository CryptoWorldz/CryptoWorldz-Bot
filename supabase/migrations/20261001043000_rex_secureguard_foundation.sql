create policy "zed_runtime_bridge" on public.secureguard_events
for all to anon using (public.zed_runtime_authorized()) with check (public.zed_runtime_authorized());

drop policy if exists "zed_runtime_bridge" on public.secureguard_domains;
create policy "zed_runtime_bridge" on public.secureguard_domains
for all to anon using (public.zed_runtime_authorized()) with check (public.zed_runtime_authorized());

drop policy if exists "zed_runtime_bridge" on public.secureguard_trusted_identities;
create policy "zed_runtime_bridge" on public.secureguard_trusted_identities
for all to anon using (public.zed_runtime_authorized()) with check (public.zed_runtime_authorized());

grant select, insert, update, delete on public.secureguard_challenges, public.secureguard_events, public.secureguard_domains, public.secureguard_trusted_identities to anon;
