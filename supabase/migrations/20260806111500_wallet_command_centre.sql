create table if not exists public.project_wallets (
  purpose text primary key check (purpose in ('dev','investment','treasury','rewards')),
  label text not null,
  network text not null default 'solana' check (network = 'solana'),
  public_address text check (public_address is null or char_length(public_address) between 32 and 44),
  wallet_type text not null check (wallet_type in ('owner','multisig')),
  control_policy text not null,
  status text not null default 'planned' check (status in ('planned','active','disabled')),
  contribution_enabled boolean not null default false,
  accepted_assets text[] not null default array['USDC','SOL']::text[],
  notes text not null default '',
  updated_by bigint,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists project_wallets_unique_address
  on public.project_wallets(public_address)
  where public_address is not null;

