create or replace function public.current_investment_week_start()
returns date
language sql
stable
as $$
  select date_trunc('week', timezone('Australia/Sydney', now()))::date
$$;

create or replace function public.record_investment_funding_deposit(
  p_aud_value_cents integer,
  p_usdc_amount numeric,
  p_transaction_signature text,
  p_recorded_by bigint
)
returns table(outcome text, weekly_recorded_aud_cents integer, weekly_remaining_aud_cents integer)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_settings public.investment_funding_settings%rowtype;
  v_week date := public.current_investment_week_start();
  v_used integer;
begin
  select * into v_settings from public.investment_funding_settings where id = 'global' for update;
  select coalesce(sum(aud_value_cents), 0)::integer into v_used
  from public.investment_funding_deposits
  where funding_week_start = v_week and status in ('recorded','verified');

  if p_aud_value_cents is null or p_aud_value_cents <= 0 or p_usdc_amount is null or p_usdc_amount <= 0 then
    return query select 'invalid_amount'::text, v_used, greatest(v_settings.weekly_target_aud_cents - v_used, 0);
    return;
  end if;
  if exists (select 1 from public.investment_funding_deposits where transaction_signature = p_transaction_signature) then
    return query select 'duplicate_transaction'::text, v_used, greatest(v_settings.weekly_target_aud_cents - v_used, 0);
    return;
  end if;
  if v_used + p_aud_value_cents > v_settings.weekly_target_aud_cents then
    return query select 'weekly_target_exceeded'::text, v_used, greatest(v_settings.weekly_target_aud_cents - v_used, 0);
    return;
  end if;

  insert into public.investment_funding_deposits(
    funding_week_start, aud_value_cents, usdc_amount, transaction_signature, recorded_by
  ) values (v_week, p_aud_value_cents, p_usdc_amount, p_transaction_signature, p_recorded_by);
  v_used := v_used + p_aud_value_cents;
  return query select 'recorded'::text, v_used, greatest(v_settings.weekly_target_aud_cents - v_used, 0);
end;
$$;

create or replace function public.get_investment_funding_status()
returns table(
  funding_week_start date,
  funding_asset text,
  weekly_target_aud_cents integer,
  recorded_aud_cents integer,
  remaining_aud_cents integer,
  auto_transfer_enabled boolean
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_settings public.investment_funding_settings%rowtype;
  v_week date := public.current_investment_week_start();
  v_used integer;
begin
  select * into v_settings from public.investment_funding_settings where id = 'global';
  select coalesce(sum(d.aud_value_cents), 0)::integer into v_used
  from public.investment_funding_deposits d
  where d.funding_week_start = v_week and d.status in ('recorded','verified');
  return query select v_week, v_settings.funding_asset, v_settings.weekly_target_aud_cents,
    v_used, greatest(v_settings.weekly_target_aud_cents - v_used, 0), v_settings.auto_transfer_enabled;
end;
$$;

create or replace function public.claim_auto_dca_schedule(p_worker_id text)
returns setof public.auto_dca_schedules
language plpgsql
security definer
set search_path = ''
as $$
declare
  claimed public.auto_dca_schedules%rowtype;
  settings public.auto_dca_settings%rowtype;
  v_today_count integer := 0;
  v_today_spent numeric := 0;
  v_week_spent numeric := 0;
begin
  if p_worker_id is null or char_length(trim(p_worker_id)) < 3 then return; end if;

  select * into settings from public.auto_dca_settings where id = 1 for update;
  if not found or not settings.enabled or not settings.execution_enabled or settings.paused or settings.emergency_stop or settings.wallet_address is null then return; end if;
  if settings.multiwallet_enabled or settings.randomized_execution or not settings.buy_only then return; end if;

  select count(*)::integer, coalesce(sum(input_amount),0),
    coalesce(sum(input_amount) filter (where started_at >= date_trunc('week', now())),0)
  into v_today_count, v_today_spent, v_week_spent
  from public.auto_dca_executions
  where status = 'success'
    and started_at >= date_trunc('day', now());

  if v_today_count >= settings.max_buys_per_day or v_today_spent >= settings.max_daily_amount or v_week_spent >= settings.max_weekly_amount then return; end if;

  select * into claimed
  from public.auto_dca_schedules
  where status = 'active'
    and input_currency = settings.allowed_input_currency
    and amount_per_buy <= settings.max_order_amount
    and v_today_spent + amount_per_buy <= settings.max_daily_amount
    and v_week_spent + amount_per_buy <= settings.max_weekly_amount
    and completed_buys < order_count
    and next_run_at is not null and next_run_at <= now()
    and (locked_until is null or locked_until < now())
  order by next_run_at asc, created_at asc
  for update skip locked
  limit 1;
  if not found then return; end if;

  update public.auto_dca_schedules
  set locked_by = p_worker_id,
      locked_until = now() + interval '2 minutes',
      started_at = coalesce(started_at, now()),
      updated_at = now()
  where id = claimed.id
  returning * into claimed;
  return next claimed;
end;
$$;

