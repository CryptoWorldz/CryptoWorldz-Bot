create or replace function public.grace_claim_due_targets(
  p_workspace_id uuid,
  p_limit integer default 10
)
returns table (
  target_id bigint,
  post_id uuid,
  account_id bigint,
  platform text,
  account_key text,
  display_name text,
  handle text,
  credential_secret_ref text,
  monthly_budget_usd numeric,
  caption text,
  link_url text,
  media jsonb,
  attempt_count integer
)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  return query
  with candidates as (
    select target.id
    from public.grace_post_targets target
    join public.grace_posts post on post.id = target.post_id
    join public.grace_social_accounts account on account.id = target.account_id
    join public.grace_settings settings on settings.workspace_id = target.workspace_id
    where target.workspace_id = p_workspace_id
      and target.status = 'queued'
      and target.scheduled_for <= now()
      and coalesce(target.next_attempt_at, target.scheduled_for) <= now()
      and post.status = 'approved'
      and account.status = 'active'
      and settings.posting_enabled = true
      and settings.paused = false
      and settings.emergency_stop = false
    order by target.scheduled_for asc, target.id asc
    for update of target skip locked
    limit greatest(1, least(coalesce(p_limit, 10), 25))
  ), claimed as (
    update public.grace_post_targets target
    set status = 'publishing',
        attempt_count = target.attempt_count + 1,
        last_attempt_at = now(),
        updated_at = now()
    from candidates
    where target.id = candidates.id
    returning target.*
  )
  select
    claimed.id,
    claimed.post_id,
    claimed.account_id,
    account.platform,
    account.account_key,
    account.display_name,
    account.handle,
    account.credential_secret_ref,
    account.monthly_budget_usd,
    claimed.caption,
    post.link_url,
    claimed.media,
    claimed.attempt_count
  from claimed
  join public.grace_posts post on post.id = claimed.post_id
  join public.grace_social_accounts account on account.id = claimed.account_id;
end;
$$;

