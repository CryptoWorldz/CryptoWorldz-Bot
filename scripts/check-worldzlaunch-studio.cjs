#!/usr/bin/env node
const fs=require('node:fs'),assert=require('node:assert/strict');
const read=p=>fs.readFileSync(p,'utf8');
const fee=JSON.parse(read('worldzpad-omnichain/chain-native-fee-builder.v1.json'));
const flow=JSON.parse(read('worldzpad-mainnet/fairfee/worldz-fee-flow.v3.json'));
const home=read('worldzlaunch.com/index.html');
const studio=read('worldzlaunch.com/fee-distribution-studio/index.html');
assert.equal(fee.publicMinimumPercent,.25);
assert.equal(fee.publicMaximumPercent,3);
assert.equal(fee.preferredIncrementPercent,.25);
assert.equal(fee.defaultPercent,1);
for(const key of ['solana','ethereum','base','bnb','hyperevm','robinhood'])assert.equal(fee.chains[key].creatorExperience.minPercent,.25,key);
assert.equal(fee.chains.solana.routeOverrides.worldzCurve.creatorChoiceTemporarilyLocked,true);
assert.equal(fee.chains.solana.routeOverrides.worldzCurve.currentReviewedDevnetFeePercent,2);
assert.deepEqual(flow.creatorChoice.allowedWorldzContributionPercent,[3,5,8]);
assert.equal(flow.safety.automaticMainnetRoutingEnabled,false);
assert.equal(flow.safety.treasuryMultisigRequired,false);
assert.equal(flow.treasuryLane.governance.mode,'DEV_WALLET_ONLY');
assert.equal(flow.treasuryLane.split.devWalletTreasuryPercent,100);
assert.equal(flow.treasuryLane.percentOfWorldzContribution,20);
assert.equal(flow.treasuryLane.effectivePercentOfWorldzContribution.devWalletTreasury,20);
assert.match(home,/id="menu"/);assert.match(home,/id="drawer"/);
assert.match(home,/\/assets\/worldz-incorporated-profile\.png/);
assert.match(home,/\/fee-distribution-studio\//);
assert.match(home,/SparkyWorldzBot/);
assert.doesNotMatch(home,/DipShitBossBot|ASK DIPSHIT/i);
assert.match(studio,/min="\.25" max="3" step="\.25"/);
assert.match(studio,/DEV_WALLET_ONLY/);
assert.match(studio,/DRAFT_ONLY_MAINNET_GATED/);
assert.match(studio,/total!==100/);
assert.match(studio,/navigator\.clipboard\.writeText/);
assert.equal(fs.existsSync('worldzlaunch.com/assets/worldz-incorporated-profile.jpg'),true,'Worldz logo image must be committed');
console.log('WorldzLaunchPad fee + treasury + navigation + asset checks passed');
